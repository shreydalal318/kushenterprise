// Embeds the logo and Inter font files as base64 so the PDF renderer has no runtime file paths
// (works identically inside Next.js bundles, scripts and tests). Run after changing brand assets.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { createRequire } from 'node:module';

const here = dirname(new URL(import.meta.url).pathname);
const require = createRequire(import.meta.url);
const fontDir = join(dirname(require.resolve('@fontsource/inter/package.json')), 'files');
const b64 = (p) => readFileSync(p).toString('base64');

const faces = [];
for (const [weight, style] of [['400', 'normal'], ['400', 'italic'], ['600', 'normal'], ['600', 'italic'], ['700', 'normal']]) {
  for (const subset of ['latin', 'latin-ext']) {
    faces.push({ weight, style, subset, data: b64(join(fontDir, `inter-${subset}-${weight}-${style}.woff2`)) });
  }
}
const logo = b64(resolve(here, '../../../brand/logo-primary-lockup-trim.png'));

writeFileSync(join(here, '../src/assets.generated.ts'), `// Generated by scripts/gen-assets.mjs. Do not edit.
/* eslint-disable */
export const LOGO_PNG_BASE64 = ${JSON.stringify(logo)};
export const INTER_FACES: { weight: string; style: string; subset: 'latin' | 'latin-ext'; data: string }[] = ${JSON.stringify(faces)};
`);
console.log(`assets.generated.ts written (${faces.length} font faces, logo ${Math.round(logo.length / 1024)} KB base64)`);
